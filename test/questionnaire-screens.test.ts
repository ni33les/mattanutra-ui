import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { deserializeState, createInitialState, fastForwardQuestionnaire } from "@/lib/questionnaire/engine";
import { chatAnswersFromAssessment, parseChatDraft, updateChatDraft } from "@/lib/questionnaire/browser-draft";
import { toAssessmentAnswers } from "@/lib/questionnaire/normalize";
import { advanceScreen, createScreenState, fastForwardScreens, labsValid, migrateScreenState, openScreen, previousScreen, questionnaireScreens, screenComplete, screenDefinition, screenProgress, screenQuestionnaireComplete, screenTurns, toggleScreenChoice, updateScreenAnswer, visibleScreens } from "@/lib/questionnaire/screens";

const blank = () => createScreenState("en", "screen-test");
const complete = () => updateScreenAnswer(fastForwardScreens(blank()), "disclosure", true);

describe("v15.5 grouped questionnaire", () => {
  it("uses the same 24 screens and stable clinical keys for EN/TH, and preserves v6 agents", () => {
    assert.equal(questionnaireScreens.length, 24);
    const en = screenDefinition(blank());
    const th = screenDefinition({ ...blank(), locale: "th" });
    assert.deepEqual(en.turns.map(turn => turn.k), th.turns.map(turn => turn.k));
    assert.equal(en.turns.find(turn => turn.k === "sex")?.q, "What is your sex?");
    for (const key of ["budget", "maxPills", "form", "protein", "fitness", "tracker", "precisionGate"]) assert.ok(!en.turns.some(turn => turn.k === key));
    assert.equal(createInitialState({ locale: "en", channel: "agent" }).version, "v6-conversational");
    const legacy = fastForwardQuestionnaire(createInitialState({ locale: "th", channel: "agent" }));
    assert.equal(legacy.ok, true);
  });
  it("requires every grouped answer before moving forward and keeps answers when going back", () => {
    let state = openScreen(blank(), "basics");
    state = updateScreenAnswer(state, "age", "26-35");
    assert.equal(advanceScreen(state).screenId, "basics");
    state = updateScreenAnswer(state, "sex", "male");
    state = advanceScreen(state);
    assert.equal(state.screenId, "sleep");
    assert.equal(previousScreen(state).screenId, "basics");
    assert.equal(previousScreen(state).answers.age, "26-35");
  });
  it("allows omitted optional fields but rejects invalid supplied optional values and malformed saved navigation", () => {
    const repro = questionnaireScreens.find(screen => screen.id === "repro")!;
    let state = updateScreenAnswer(blank(), "sex", "female");
    state = updateScreenAnswer(state, "reproStatus", "none");
    assert.equal(screenComplete(state, repro), true);
    assert.equal(screenComplete(updateScreenAnswer(state, "menopause", "invalid-option"), repro), false);
    assert.equal(screenComplete(updateScreenAnswer(state, "firstName", 42), questionnaireScreens[0]), false);
    assert.equal(deserializeState(JSON.stringify({ ...state, completedScreens: {} })), null);
    assert.equal(deserializeState(JSON.stringify({ ...state, screenReview: "yes" })), null);
    assert.equal(deserializeState(JSON.stringify({ ...state, autoFilled: [42] })), null);
  });
  it("prunes conditional answers without clearing unrelated later screens", () => {
    let state = complete();
    state = updateScreenAnswer(state, "sex", "female");
    state = updateScreenAnswer(state, "reproStatus", "none");
    state = updateScreenAnswer(state, "flow", "heavy");
    state = updateScreenAnswer(state, "reproStatus", "pregnant");
    assert.equal(state.answers.flow, undefined);
    state = updateScreenAnswer(state, "meds", "yes");
    state = updateScreenAnswer(state, "medTypes", ["other"]);
    state = updateScreenAnswer(state, "otherMed", "A medication");
    state = updateScreenAnswer(state, "meds", "none");
    assert.equal(state.answers.medTypes, undefined);
    assert.equal(state.answers.otherMed, undefined);
    assert.ok(state.answers.diet);
    assert.equal(state.answers.disclosure, false);
  });
  it("starts measurements at configured defaults and preserves edits, clears and unknowns through navigation and resume", () => {
    let state = openScreen(blank(), "body");
    const body = questionnaireScreens.find(screen => screen.id === "body")!;
    assert.equal(screenComplete(state, body), true);
    assert.equal(state.answers.height, "175");
    assert.equal(state.answers.weight, "72");
    assert.equal(toAssessmentAnswers(state.answers).heightCm, "175");
    assert.equal(toAssessmentAnswers(state.answers).weightKg, "72");
    state = updateScreenAnswer(state, "heightStatus", "unknown");
    state = updateScreenAnswer(state, "weight", "0");
    assert.equal(screenComplete(state, body), false);
    state = updateScreenAnswer(state, "weight", "73.5");
    assert.equal(screenComplete(state, body), true);
    const payload = toAssessmentAnswers(state.answers);
    assert.equal(payload.heightCm, "");
    assert.equal(payload.weightKg, "73.5");
    assert.deepEqual(payload.answerStatus, { height: "unknown", weight: "known" });
    assert.equal(state.answers.height, null);
    state = openScreen(migrateScreenState(deserializeState(JSON.stringify(state))!), "body");
    assert.equal(state.answers.heightStatus, "unknown");
    assert.equal(state.answers.height, null);
    assert.equal(state.answers.weight, "73.5");
    state = updateScreenAnswer(state, "heightStatus", "unanswered");
    state = updateScreenAnswer(state, "weight", "");
    state = openScreen(migrateScreenState(deserializeState(JSON.stringify(state))!), "body");
    assert.equal(state.answers.height, "");
    assert.equal(state.answers.weight, "");
    assert.equal(screenComplete(state, body), false);
  });
  it("validates labs and future dates, keeps chosen units and clears stale results on gate changes", () => {
    let state = updateScreenAnswer(blank(), "labsHave", "yes");
    state = updateScreenAnswer(state, "lab_vitd", "-1");
    assert.equal(labsValid(state), false);
    state = updateScreenAnswer(state, "lab_vitd", "88");
    state = updateScreenAnswer(state, "unit_vitd", "nmol/L");
    state = updateScreenAnswer(state, "labDate", "2999-01-01");
    assert.equal(labsValid(state), false);
    state = updateScreenAnswer(state, "labDate", "2025-02-31");
    assert.equal(labsValid(state), false);
    state = updateScreenAnswer(state, "labDate", "2025-02-20");
    assert.equal(labsValid(state), true);
    assert.equal(toAssessmentAnswers(state.answers).labUnits.vitd, "nmol/L");
    assert.equal(toAssessmentAnswers(state.answers).labDate, "2025-02-20");
    state = updateScreenAnswer(state, "labsHave", "notnow");
    assert.equal(labsValid(state), true);
    assert.deepEqual(toAssessmentAnswers(state.answers).labs, {});
    assert.equal(state.answers.labDate, undefined);
  });
  it("enforces exclusive choices, valid option values and the three-goal limit", () => {
    const family = screenDefinition(blank()).turns.find(turn => turn.k === "family")!;
    let state = toggleScreenChoice(blank(), family, "heart");
    state = toggleScreenChoice(state, family, "unsure");
    assert.deepEqual(state.answers.family, ["unsure"]);
    state = toggleScreenChoice(state, family, "diabetes");
    assert.deepEqual(state.answers.family, ["diabetes"]);
    const goals = screenDefinition(state).turns.find(turn => turn.k === "goals")!;
    for (const key of ["energy", "sleep", "focus", "longevity"]) state = toggleScreenChoice(state, goals, key);
    assert.deepEqual(state.answers.goals, ["energy", "sleep", "focus"]);
    const goalsScreen = questionnaireScreens.find(screen => screen.id === "goals")!;
    assert.equal(screenComplete(updateScreenAnswer(state, "goals", ["invented"]), goalsScreen), false);
  });
  it("lets users edit inferred vegan answers and preserves explicit food preferences when changing diet", () => {
    let state = updateScreenAnswer(blank(), "diet", "vegan");
    assert.deepEqual(state.autoFilled, ["f_redmeat", "f_fish", "f_dairy", "f_eggs"]);
    state = openScreen(state, "foodA", true);
    assert.ok(screenTurns(state, questionnaireScreens.find(screen => screen.id === "foodA")!).some(turn => turn.k === "f_redmeat"));
    state = updateScreenAnswer(state, "f_redmeat", "1-2");
    state = updateScreenAnswer(state, "diet", "balanced");
    assert.equal(state.answers.f_redmeat, "1-2");
    assert.equal(state.answers.f_fish, undefined);
    assert.deepEqual(state.autoFilled, []);
  });
  it("requires separate final disclosure, edits preserve later answers and progress is completion only", () => {
    let state = fastForwardScreens(blank());
    assert.equal(state.answers.consentSafety, true);
    assert.equal(state.answers.disclosure, false);
    assert.equal(toAssessmentAnswers(state.answers).disclosure, false);
    assert.equal(screenQuestionnaireComplete(state), false);
    assert.equal(screenProgress(state), 100);
    state = updateScreenAnswer(state, "disclosure", true);
    assert.equal(screenQuestionnaireComplete(state), true);
    state = openScreen(state, "goals", true);
    state = updateScreenAnswer(state, "goals", ["sleep"]);
    assert.equal(state.answers.labsHave, "no");
    assert.equal(advanceScreen(state).screenReview, true);
    assert.equal(screenQuestionnaireComplete(state), false);
    assert.equal(screenProgress(blank()), 0);
  });
  it("round-trips v15 draft navigation and unknown values without claiming unanswered legacy defaults", () => {
    const state = updateScreenAnswer(openScreen(blank(), "body"), "heightStatus", "unknown");
    assert.equal(deserializeState(JSON.stringify(state))?.screenId, "body");
    assert.equal(migrateScreenState(deserializeState(JSON.stringify(state))!).answers.heightStatus, "unknown");
    const draft = { version: 1 as const, state, revision: 0, captured: null, contactEmail: null, paymentId: null, updatedAt: Date.now() };
    assert.equal(parseChatDraft(JSON.stringify(draft))?.state.screenId, "body");
    assert.equal(migrateScreenState(createInitialState({ locale: "en" })).answers.heightStatus, "unanswered");
    assert.ok(!visibleScreens(updateScreenAnswer(blank(), "sex", "male")).some(screen => screen.id === "repro"));
  });
  it("normalizes resumed edited nested food/labs fields with flat edits taking precedence and invalidates a capture receipt", () => {
    const raw = chatAnswersFromAssessment({ foodFrequency: { fish: "often" }, labs: { vitd: "40" }, labUnits: { vitd: "ng/mL" }, heightCm: "180", weightKg: "80" });
    let state = migrateScreenState({ ...blank(), answers: raw });
    state = updateScreenAnswer(state, "labsHave", "yes");
    state = updateScreenAnswer(state, "f_fish", "never");
    state = updateScreenAnswer(state, "lab_vitd", "");
    state = updateScreenAnswer(state, "unit_vitd", "nmol/L");
    const payload = toAssessmentAnswers(state.answers);
    assert.equal(payload.foodFrequency.fish, "never");
    assert.equal(payload.labs.vitd, undefined);
    assert.equal(payload.labUnits.vitd, "nmol/L");
    const before = { ...complete(), planId: "plan-1" };
    const draft = { version: 1 as const, state: before, revision: 3, captured: { planId: "plan-1", revision: 3 }, contactEmail: null, paymentId: null, updatedAt: Date.now() };
    assert.equal(updateChatDraft(draft, updateScreenAnswer(before, "avoid", "tofu")).captured, null);
    assert.equal(updateChatDraft(draft, openScreen(before, "goals", true)).captured?.planId, "plan-1");
  });
});
